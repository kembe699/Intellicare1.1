// Ensure password_reset_tokens table exists — bootstrap runs once at boot
// against the app's own default database only. Any newly-provisioned tenant
// database already has this table (it's cloned from that same default
// database's current schema — see scripts/provisionTenant.js).
(async () => {
  try {
    const { sequelize } = require('../models');
    await sequelize.query(`
      CREATE TABLE IF NOT EXISTS password_reset_tokens (
        id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id VARCHAR(36) NOT NULL,
        token VARCHAR(255) NOT NULL UNIQUE,
        expires_at TIMESTAMP NOT NULL,
        used BOOLEAN DEFAULT FALSE,
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
      )
    `);
    await sequelize.query(`
      CREATE INDEX IF NOT EXISTS idx_password_reset_tokens_token ON password_reset_tokens(token)
    `);
    await sequelize.query(`
      CREATE INDEX IF NOT EXISTS idx_password_reset_tokens_user_id ON password_reset_tokens(user_id)
    `);
  } catch (error) {
    console.error('Error creating password_reset_tokens table:', error);
  }
})();

async function loadUserBranchContext(sequelize, user) {
  try {
    const [rows] = await sequelize.query(`
      SELECT b.id, b.name, b.facility_id, COALESCE(ub.is_primary, false) AS is_primary
      FROM user_branches ub
      INNER JOIN branches b ON b.id = ub.branch_id
      WHERE ub.user_id = ?
      ORDER BY ub.is_primary DESC, b.name ASC
    `, {
      replacements: [user.id]
    });

    if (rows.length > 0) {
      const branches = rows.map((row) => ({
        id: row.id,
        name: row.name,
        facilityId: row.facility_id,
        isPrimary: !!row.is_primary,
      }));
      const primaryBranch = branches.find((branch) => branch.isPrimary) || branches[0];
      return { branches, primaryBranch };
    }
  } catch (error) {
    console.log('Auth branch context fallback:', error.message);
  }

  if (user.branch_id) {
    try {
      const [fallbackRows] = await sequelize.query(`
        SELECT id, name, facility_id
        FROM branches
        WHERE id = ?
        LIMIT 1
      `, {
        replacements: [user.branch_id]
      });

      if (fallbackRows.length > 0) {
        const fallbackBranch = {
          id: fallbackRows[0].id,
          name: fallbackRows[0].name,
          facilityId: fallbackRows[0].facility_id,
          isPrimary: true,
        };
        return { branches: [fallbackBranch], primaryBranch: fallbackBranch };
      }
    } catch (error) {
      console.log('Auth branch name lookup fallback:', error.message);
    }

    const fallbackBranch = {
      id: user.branch_id,
      name: `Branch ${user.branch_id}`,
      facilityId: null,
      isPrimary: true,
    };
    return { branches: [fallbackBranch], primaryBranch: fallbackBranch };
  }

  // Last resort: a user with no user_branches row and no branch_id would
  // otherwise sign in with no branch at all — the token is valid, the welcome
  // toast fires, and then the app renders nothing, because every branch-scoped
  // screen has no branch to scope to. That is exactly what a user created
  // through Setup > Users looked like, since that form leaves branch_id null.
  //
  // Falling back to the facility's main branch (or the only branch, if there is
  // just one) means such an account is usable instead of blank. It is a
  // read-only default: nothing is written here, so an admin assigning a real
  // branch later still wins.
  try {
    const [mainRows] = await sequelize.query(`
      SELECT id, name, facility_id
      FROM branches
      WHERE is_active IS NOT FALSE
      ORDER BY is_main_branch DESC, id ASC
      LIMIT 1
    `);
    if (mainRows.length > 0) {
      const fallback = {
        id: mainRows[0].id,
        name: mainRows[0].name,
        facilityId: mainRows[0].facility_id,
        isPrimary: true,
      };
      return { branches: [fallback], primaryBranch: fallback };
    }
  } catch (error) {
    console.log('Auth default-branch fallback failed:', error.message);
  }

  return { branches: [], primaryBranch: null };
}

// privileges is the resolved role_privileges set for this user's role — the
// same data authorize() checks server-side (src/server/middleware/authorize.js),
// exposed here so the frontend's sidebar/route guards can check the same
// thing instead of a hardcoded role list. admin gets [] on purpose: the
// frontend already carries isAdmin and should bypass on that rather than
// receiving every one of the 75+ catalog keys on every login.
async function buildUserResponse(user, branchContext, sequelize, schemaName) {
  let privileges = [];
  let additionalRoles = [];
  try {
    const [rows] = await sequelize.query(
      'SELECT role_key FROM user_additional_roles WHERE user_id = ?',
      { replacements: [user.id] }
    );
    additionalRoles = rows.map((r) => r.role_key);
  } catch (_e) { /* table not ensured yet on this tenant — treat as none */ }

  if (user.role !== 'admin') {
    try {
      const { getRolePrivileges } = require('../middleware/authorize');
      const grants = await getRolePrivileges(sequelize, schemaName);
      // Effective privileges are the union of the primary role's grants and
      // every additional role's grants — permissions combine, not replace.
      const combined = new Set(grants.get(user.role) || []);
      for (const roleKey of additionalRoles) {
        for (const key of grants.get(roleKey) || []) combined.add(key);
      }
      privileges = [...combined];
    } catch (err) {
      console.error(`Could not resolve privileges for role "${user.role}" on ${schemaName}:`, err.message);
    }
  }
  return {
    id: user.id,
    email: user.email,
    displayName: user.display_name,
    role: user.role,
    additionalRoles,
    clinicId: user.clinic_id,
    clinic: user.clinic_id,
    branchId: branchContext.primaryBranch?.id || user.branch_id || null,
    primaryBranchId: branchContext.primaryBranch?.id || user.branch_id || null,
    primaryBranchName: branchContext.primaryBranch?.name || null,
    accessibleBranches: branchContext.branches,
    isAdmin: user.role === 'admin',
    status: user.status,
    currentRoomId: user.current_room_id || null,
    privileges,
  };
}

// Note: /verify-branch-access, /forgot-password, /verify-reset-token, and
// /reset-password used to each be implemented twice — once here, once as a
// standalone app.post/app.get handler in index.js registered BEFORE this
// router is mounted. Express matches the first-registered route and stops,
// so the copies that were here were permanently unreachable dead code — a
// real drift risk, since a future fix applied only to the dead copy would
// silently not take effect. Removed; the live implementations are in index.js.

// Login endpoint — code selects which client/instance to authenticate against
// (typed on the login page, e.g. "nationmc"); email/password are then checked
// against that client's own, fully separate database.
router.post('/login', authSourceLimiter, authLimiter, async (req, res) => {
  try {
    const { code, email, password } = req.body;

    if (!code || !email || !password) {
      return res.status(400).json({ error: 'Code, email, and password are required' });
    }

    const client = await Client.findOne({ where: { code: String(code).trim().toLowerCase() } });
    if (!client) {
      return res.status(401).json({ error: 'Unknown instance code' });
    }
    // No self-service reactivation path here (billing is admin-managed, not
    // client-paid) — a suspended client's login is simply blocked.
    if (client.status !== 'active') {
      return res.status(403).json({ error: 'This account has been suspended. Please contact support.' });
    }

    let tenantConnection;
    try {
      tenantConnection = await getTenantConnection(client.schema_name);
    } catch (connErr) {
      console.error('Tenant connection error:', connErr);
      return res.status(503).json({ error: 'Could not connect to your instance, please try again shortly' });
    }
    const { sequelize, models } = tenantConnection;

    // Find user by email
    const user = await models.User.findOne({
      where: { email: email.toLowerCase() },
    });

    if (!user) {
      return res.status(401).json({ error: 'Invalid email or password' });
    }

    // Check if user is active
    if (!user.is_active) {
      return res.status(401).json({ error: 'Account is disabled' });
    }

    // Verify password
    const isValidPassword = await bcrypt.compare(password, user.password_hash);
    if (!isValidPassword) {
      return res.status(401).json({ error: 'Invalid email or password' });
    }

    const branchContext = await loadUserBranchContext(sequelize, user);

    // Generate JWT token
    const token = jwt.sign(
      {
        userId: user.id,
        email: user.email,
        role: user.role,
        clinicId: user.clinic_id,
        branchId: branchContext.primaryBranch?.id || user.branch_id || null,
        schemaName: client.schema_name,
        // Carried in the token (not just the /login response body) so /verify can hand
        // it back on every page refresh without an extra Client lookup — the frontend
        // needs this for tenant-specific features (e.g. a dpoc-only quick-register flow
        // on the LIS orders page) that have no other way to tell tenants apart.
        clientCode: client.code
      },
      JWT_SECRET,
      { expiresIn: '24h' }
    );

    // Return user data and token
    res.json({
      token,
      user: { ...(await buildUserResponse(user, branchContext, sequelize, client.schema_name)), tenantCode: client.code },
      client: { name: client.name, code: client.code }
    });
  } catch (error) {
    console.error('Login error:', error);
    res.status(500).json({ error: 'Login failed' });
  }
});

// Verify token endpoint
router.get('/verify', async (req, res) => {
  try {
    const token = req.headers.authorization?.replace('Bearer ', '');
    
    if (!token) {
      return res.status(401).json({ error: 'No token provided' });
    }

    const decoded = jwt.verify(token, JWT_SECRET);
    if (!decoded.schemaName) return res.status(401).json({ error: 'Session is out of date, please log in again' });
    const { sequelize, models } = await getTenantConnection(decoded.schemaName);

    // Get fresh user data
    const user = await models.User.findByPk(decoded.userId);
    if (!user || !user.is_active) {
      return res.status(401).json({ error: 'Invalid token' });
    }

    const branchContext = await loadUserBranchContext(sequelize, user);

    // A token minted before clientCode existed carries no clientCode claim at all —
    // resolved fresh here (by schema, the one thing every token has always carried)
    // so a plain page refresh picks it up immediately, not only after an explicit
    // logout/login or a 24h token expiry.
    let clientCode = decoded.clientCode;
    if (!clientCode) {
      const client = await Client.findOne({ where: { schema_name: decoded.schemaName } });
      clientCode = client?.code || null;
    }

    // Re-issue the token when the identity it carries has drifted from the
    // database.
    //
    // clinicId is checked here for the same reason role and branch are, and its
    // absence was a real fault: every query for a non-admin is scoped by the
    // clinicId in the token, so a user whose clinic is corrected keeps reading
    // an empty clinic until the token expires — up to 24 hours, and a page
    // refresh does not help, because /me only handed back a new token when the
    // role or branch differed. That is what left a pharmacy account staring at
    // an empty inventory after its clinic had already been fixed. clientCode is
    // checked the same way, for the same reason — otherwise a tenant-gated
    // feature stays invisible to an already-logged-in user for up to 24h.
    const freshToken = (decoded.role !== user.role
      || decoded.clinicId !== user.clinic_id
      || decoded.branchId !== (branchContext.primaryBranch?.id || user.branch_id || null)
      || decoded.clientCode !== clientCode)
      ? jwt.sign(
          {
            userId: user.id,
            email: user.email,
            role: user.role,
            clinicId: user.clinic_id,
            branchId: branchContext.primaryBranch?.id || user.branch_id || null,
            schemaName: decoded.schemaName,
            clientCode
          },
          JWT_SECRET,
          { expiresIn: '24h' }
        )
      : null;

    res.json({
      user: { ...(await buildUserResponse(user, branchContext, sequelize, decoded.schemaName)), tenantCode: clientCode },
      ...(freshToken && { token: freshToken })
    });
  } catch (error) {
    console.error('Token verification error:', error);
    res.status(401).json({ error: 'Invalid token' });
  }
});


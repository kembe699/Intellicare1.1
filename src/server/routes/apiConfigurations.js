const express = require('express');
const crypto = require('crypto');
const { sequelize } = require('../models');
const { authorize } = require('../middleware/authorize');
const router = express.Router();

// ─── Table Bootstrap ──────────────────────────────────────────────────────────
// Auto-creates the table on first load (safe to re-run).
(async () => {
  try {
    await sequelize.query(`
      CREATE TABLE IF NOT EXISTS api_integration_tokens (
        id SERIAL PRIMARY KEY,
        config_type   VARCHAR(100) NOT NULL,
        label         VARCHAR(255),
        token_hash    VARCHAR(64) NOT NULL UNIQUE,
        token_preview VARCHAR(30),
        is_active     BOOLEAN DEFAULT TRUE,
        created_by    VARCHAR(255),
        created_at    TIMESTAMP DEFAULT NOW(),
        last_used_at  TIMESTAMP
      )
    `);
    await sequelize.query(`
      CREATE INDEX IF NOT EXISTS idx_api_tokens_config_type ON api_integration_tokens(config_type)
    `);
    await sequelize.query(`
      CREATE INDEX IF NOT EXISTS idx_api_tokens_token_hash ON api_integration_tokens(token_hash)
    `);
    console.log('✅ api_integration_tokens table ready');
  } catch (e) {
    console.warn('API tokens table bootstrap warning:', e.message);
  }
})();

// ─── Helpers ─────────────────────────────────────────────────────────────────
function hashToken(rawToken) {
  return crypto.createHash('sha256').update(rawToken).digest('hex');
}

// dbName is embedded in the raw token itself (ic-<prefix>:<dbName>:<random>) — this
// token is presented cold by the desktop Lab Agent with no session/JWT and no other
// way to say which tenant it belongs to, and /api/lab-integration/receive (where it's
// checked) is a public route that never resolves tenant context on its own. Without
// this, verification could only ever check the app's single hardcoded default
// database, so a token generated by any other tenant would never be found there —
// exactly the "token rejected" symptom this fixes. Safe to embed: db_name is always
// plain alnum+underscore (see tenantDb.js), never contains ':'.
function generateToken(configType, dbName) {
  const prefix = configType.replace(/[^a-zA-Z0-9]/g, '').toLowerCase().slice(0, 8);
  const random = crypto.randomBytes(32).toString('base64').replace(/[+/=]/g, '').slice(0, 40);
  return `ic-${prefix}:${dbName}:${random}`;
}


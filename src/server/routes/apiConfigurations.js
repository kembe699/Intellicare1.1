// ─── GET /api/configurations ──────────────────────────────────────────────────
// Returns all config type definitions plus their active token status.
router.get('/', async (req, res) => {
  try {
    // Fetch all active tokens for every config type
    const [rows] = await sequelize.query(`
      SELECT config_type, token_preview, created_by, created_at, last_used_at, id, is_active
      FROM api_integration_tokens
      ORDER BY created_at DESC
    `);

    // Map: configType → most-recent active token row
    const tokenMap = {};
    for (const row of rows) {
      if (!tokenMap[row.config_type] && row.is_active) {
        tokenMap[row.config_type] = row;
      }
    }

    const data = CONFIG_TYPES.map((ct) => ({
      ...ct,
      token: tokenMap[ct.id] || null,
    }));

    res.json({ success: true, data });
  } catch (error) {
    console.error('API Configurations list error:', error);
    res.status(500).json({ error: 'Failed to load configurations' });
  }
});

// ─── POST /api/configurations/generate ───────────────────────────────────────
// Generates a new token for a given configType.
// The full raw token is returned ONCE — it is not stored.
// Only the SHA-256 hash is persisted.
router.post('/generate', authorize(['admin']), async (req, res) => {
  try {
    const { configType, label } = req.body;

    if (!configType) {
      return res.status(400).json({ error: 'configType is required' });
    }

    const isKnown = CONFIG_TYPES.find((ct) => ct.id === configType);
    if (!isKnown) {
      return res.status(400).json({ error: 'Unknown config type' });
    }

    // Revoke any existing active tokens for this config type first
    await sequelize.query(`
      UPDATE api_integration_tokens
      SET is_active = FALSE
      WHERE config_type = ? AND is_active = TRUE
    `, { replacements: [configType] });

    // Generate raw token
    const rawToken = generateToken(configType, req.tenantDbName);
    const tokenHash = hashToken(rawToken);
    const tokenPreview = rawToken.slice(0, 20) + '••••••••';

    const createdBy = req.user?.email || req.user?.displayName || 'System';

    await sequelize.query(`
      INSERT INTO api_integration_tokens 
        (config_type, label, token_hash, token_preview, is_active, created_by, created_at)
      VALUES (?, ?, ?, ?, TRUE, ?, NOW())
    `, {
      replacements: [configType, label || isKnown.label, tokenHash, tokenPreview, createdBy]
    });

    // Return the full raw token ONCE — it cannot be retrieved again
    res.json({
      success: true,
      token: rawToken,
      tokenPreview,
      message: 'Copy this token now. It will not be shown again.',
    });
  } catch (error) {
    console.error('Token generation error:', error);
    res.status(500).json({ error: 'Failed to generate token' });
  }
});

// ─── DELETE /api/configurations/:id/revoke ────────────────────────────────────
// Revokes (deactivates) a specific token by ID.
router.delete('/:id/revoke', authorize(['admin']), async (req, res) => {
  try {
    const { id } = req.params;

    await sequelize.query(`
      UPDATE api_integration_tokens
      SET is_active = FALSE
      WHERE id = ?
    `, { replacements: [id] });

    res.json({ success: true, message: 'Token revoked successfully' });
  } catch (error) {
    console.error('Token revoke error:', error);
    res.status(500).json({ error: 'Failed to revoke token' });
  }
});


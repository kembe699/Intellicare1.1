/**
 * DDL only — creates the roles/privileges/role_privileges tables if they
 * don't exist yet. Safe to call repeatedly, and safe to call per-tenant
 * (unlike the old boot-time IIFE in routes/roles.js, which only ever ran
 * against the single default connection and never actually reached a real
 * tenant schema — seeding real data is reconcileRolePrivileges.js's job now,
 * not this function's).
 */
async function ensureRolesTables(sequelize) {
  await sequelize.query(`
    CREATE TABLE IF NOT EXISTS privileges (
      id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      privilege_key VARCHAR(150) NOT NULL UNIQUE,
      name VARCHAR(255) NOT NULL,
      module VARCHAR(100),
      description TEXT,
      created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
    )
  `);
  await sequelize.query(`
    CREATE TABLE IF NOT EXISTS roles (
      id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      role_key VARCHAR(100) NOT NULL UNIQUE,
      name VARCHAR(255) NOT NULL,
      description TEXT,
      is_system BOOLEAN DEFAULT FALSE,
      created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
      updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
    )
  `);
  await sequelize.query(`
    CREATE TABLE IF NOT EXISTS role_privileges (
      role_id INT NOT NULL,
      privilege_id INT NOT NULL,
      PRIMARY KEY (role_id, privilege_id),
      FOREIGN KEY (role_id) REFERENCES roles(id) ON DELETE CASCADE,
      FOREIGN KEY (privilege_id) REFERENCES privileges(id) ON DELETE CASCADE
    )
  `);
}

module.exports = { ensureRolesTables };

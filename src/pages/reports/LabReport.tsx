import React, { useState, useEffect, useCallback, useMemo } from 'react';
import { FlaskConical, Users, TestTube2, Wallet, Loader2, TestTube } from 'lucide-react';
import { ReportSubPageShell } from './ReportSubPageShell';
import { ReportLetterhead } from './ReportLetterhead';
import { authFetch } from '@/api/apiClient';
import { useAuth } from '@/contexts/AuthContext';
import { StatusBadge, StatusBadgeTone } from '@/components/common';
import { AdvancedDataTable } from '@/components/common/DataTable/AdvancedDataTable';
import { fmtCurrency, fmtCount, CsvColumn } from '@/utils/reportUtils';
import { toast } from '@/lib/notify';

// ── Types ────────────────────────────────────────────────────────────────

interface ByTestRow {
  testCode: string | null;
  testName: string;
  volume: number | null; // null = billed under this name but no matching LIS specimen found in period
  totalBilled: number;
  totalCollected: number;
}

interface StatusRow {
  status: string;
  count: number;
}

interface LabReportData {
  period: { dateFrom: string; dateTo: string };
  clinicId: number;
  patientVolume: { distinctPatients: number; totalTests: number };
  cashSummary: {
    totalBilled: number;
    totalCollected: number;
    collectionMethod: { exactItems: number; estimatedItems: number; note: string };
  };
  byTest: ByTestRow[];
  statusBreakdown: StatusRow[];
}

const SPECIMEN_STATUS_TONE_MAP: Record<string, StatusBadgeTone> = {
  pending_collection: 'neutral',
  routed: 'info',
  analyzed: 'warning',
  approved: 'success',
  rejected: 'danger',
};

const toLocalDateStr = (d: Date) => {
  const yyyy = d.getFullYear();
  const mm = String(d.getMonth() + 1).padStart(2, '0');
  const dd = String(d.getDate()).padStart(2, '0');
  return `${yyyy}-${mm}-${dd}`;
};

// ── Component ────────────────────────────────────────────────────────────

export default function LabReport() {
  const { user } = useAuth();
  const clinicId = user?.clinic || 1;

  const [dateFrom, setDateFrom] = useState(() => toLocalDateStr(new Date(Date.now() - 29 * 86400000)));
  const [dateTo, setDateTo] = useState(() => toLocalDateStr(new Date()));
  const [loading, setLoading] = useState(true);
  const [data, setData] = useState<LabReportData | null>(null);
  const [generatedAt, setGeneratedAt] = useState<Date | null>(null);

  const fetchData = useCallback(async () => {
    setLoading(true);
    try {
      const params = new URLSearchParams({ dateFrom, dateTo, clinic_id: String(clinicId) });
      const res = await authFetch(`/api/reports-v2/laboratory?${params}`, { credentials: 'include' });
      if (!res.ok) throw new Error('Failed to load laboratory report');
      setData(await res.json());
      setGeneratedAt(new Date());
    } catch (e: any) {
      console.error(e);
      toast.error(e?.message || 'Failed to load laboratory report');
    } finally {
      setLoading(false);
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [dateFrom, dateTo, clinicId]);

  useEffect(() => { fetchData(); }, [fetchData]);

  const byTest = data?.byTest || [];
  const statusBreakdown = data?.statusBreakdown || [];
  const collection = data?.cashSummary.collectionMethod;

  const [selectedTest, setSelectedTest] = useState('all');
  useEffect(() => { setSelectedTest('all'); }, [dateFrom, dateTo]);

  const testKey = (t: ByTestRow, i: number) => t.testCode || `${t.testName}-${i}`;
  const testOptions = useMemo(
    () => byTest.map((t, i) => ({ key: testKey(t, i), name: t.testName })),
    [byTest]
  );
  const filteredByTest = useMemo(
    () => selectedTest === 'all' ? byTest : byTest.filter((t, i) => testKey(t, i) === selectedTest),
    [byTest, selectedTest]
  );

  // Billed/Collected/Tests-Performed are derivable per test straight from the filtered
  // row; Distinct Patients is not (the backend only computes it period-wide, not
  // per-test), so that tile stays period-wide even when a single test is selected.
  const displayCash = useMemo(() => {
    if (selectedTest === 'all') return data?.cashSummary;
    const row = filteredByTest[0];
    return {
      totalBilled: row?.totalBilled || 0,
      totalCollected: row?.totalCollected || 0,
      collectionMethod: collection,
    };
  }, [data, selectedTest, filteredByTest, collection]);
  const displayTestsPerformed = selectedTest === 'all'
    ? data?.patientVolume.totalTests
    : (filteredByTest[0]?.volume ?? 0);

  const csvColumns: CsvColumn[] = [
    { header: 'Test', key: 'testName' },
    { header: 'Test Code', key: 'testCode', transform: v => v || '—' },
    { header: 'Volume', key: 'volume', transform: v => (v == null ? 'n/a' : fmtCount(v)) },
    { header: 'Total Billed', key: 'totalBilled', transform: v => fmtCurrency(v) },
    { header: 'Total Collected', key: 'totalCollected', transform: v => fmtCurrency(v) },
  ];

  return (
    <ReportSubPageShell
      title="Laboratory Report"
      description="Tests performed, patient volume and cash value generated by the lab"
      dateFrom={dateFrom}
      dateTo={dateTo}
      onDateFromChange={setDateFrom}
      onDateToChange={setDateTo}
      onRefresh={fetchData}
      loading={loading}
      csvData={filteredByTest}
      csvColumns={csvColumns}
      csvFilename={`laboratory-report-${dateFrom}-${dateTo}.csv`}
    >
      <ReportLetterhead title="Laboratory Report" dateFrom={dateFrom} dateTo={dateTo} generatedAt={generatedAt} />
      {loading && !data ? (
        <div className="flex items-center justify-center h-64">
          <Loader2 className="h-8 w-8 animate-spin text-primary" />
        </div>
      ) : (
        <div className="space-y-6">
          {/* ── Stat tiles ── */}
          <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-4">
            <div className="bg-card rounded-lg border shadow-sm p-4">
              <div className="flex items-center justify-between">
                <div>
                  <p className="text-xs uppercase tracking-wide text-muted-foreground font-medium">Lab Revenue (Billed)</p>
                  <p className="text-2xl font-bold mt-1 text-primary">{fmtCurrency(displayCash?.totalBilled)}</p>
                  <p className="text-xs text-muted-foreground mt-0.5">across matched lab line items</p>
                </div>
                <Wallet className="h-5 w-5 text-primary" />
              </div>
            </div>

            <div className="bg-card rounded-lg border shadow-sm p-4">
              <div className="flex items-center justify-between">
                <div>
                  <p className="text-xs uppercase tracking-wide text-muted-foreground font-medium">Lab Revenue (Collected)</p>
                  <p className="text-2xl font-bold mt-1 text-success">{fmtCurrency(displayCash?.totalCollected)}</p>
                  <p className="text-xs text-muted-foreground mt-0.5">
                    {collection ? `${fmtCount(collection.exactItems)} exact · ${fmtCount(collection.estimatedItems)} estimated` : '—'}
                  </p>
                </div>
                <FlaskConical className="h-5 w-5 text-primary" />
              </div>
            </div>

            <div className="bg-card rounded-lg border shadow-sm p-4">
              <div className="flex items-center justify-between">
                <div>
                  <p className="text-xs uppercase tracking-wide text-muted-foreground font-medium">Distinct Patients</p>
                  <p className="text-2xl font-bold mt-1">{fmtCount(data?.patientVolume.distinctPatients)}</p>
                  <p className="text-xs text-muted-foreground mt-0.5">had at least one lab test</p>
                </div>
                <Users className="h-5 w-5 text-primary" />
              </div>
            </div>

            <div className="bg-card rounded-lg border shadow-sm p-4">
              <div className="flex items-center justify-between">
                <div>
                  <p className="text-xs uppercase tracking-wide text-muted-foreground font-medium">Tests Performed</p>
                  <p className="text-2xl font-bold mt-1">{fmtCount(displayTestsPerformed)}</p>
                  <p className="text-xs text-muted-foreground mt-0.5">specimens registered in period</p>
                </div>
                <TestTube2 className="h-5 w-5 text-primary" />
              </div>
            </div>
          </div>

          <div className="grid grid-cols-1 lg:grid-cols-3 gap-6">
            {/* ── By Test table ── */}
            <div className="lg:col-span-2">
              <div className="mb-1.5 print:hidden">
                <p className="text-xs text-muted-foreground">Volume performed and cash value per test</p>
              </div>
              <AdvancedDataTable<ByTestRow>
                title="By Test"
                footerRow={(colSpan) => (
                  <tr className="border-t-2 border-foreground/30 bg-info-bg dark:bg-info/20 font-semibold">
                    <td colSpan={colSpan} className="px-4 py-2.5 text-sm">
                      <div className="flex justify-between items-center">
                        <span>Total Collected</span>
                        <span className="font-mono text-base border-b-2 border-double border-foreground pb-0.5">{fmtCurrency(displayCash?.totalCollected)}</span>
                      </div>
                    </td>
                  </tr>
                )}
                data={filteredByTest}
                keyExtractor={(t, i) => testKey(t, i)}
                searchable
                searchPlaceholder="Search tests..."
                emptyMessage="No lab tests found for the selected period."
                toolbarExtra={
                  <div className="flex items-center gap-2 flex-wrap">
                    <TestTube className="h-4 w-4 text-muted-foreground" />
                    <select
                      className="flex h-9 rounded-md border border-input bg-transparent px-2 py-1 text-sm shadow-sm"
                      value={selectedTest}
                      onChange={e => setSelectedTest(e.target.value)}
                    >
                      <option value="all">All tests</option>
                      {testOptions.map(o => <option key={o.key} value={o.key}>{o.name}</option>)}
                    </select>
                  </div>
                }
                columns={[
                  {
                    key: 'testName', header: 'Test', sortable: true,
                    render: (_v, t) => (
                      <>
                        {t.testName}
                        {t.testCode && <span className="ml-1.5 text-xs font-mono text-muted-foreground">{t.testCode}</span>}
                        {t.volume == null && (
                          <span className="ml-1.5 text-xs text-warning" title="Billed under this name but no matching LIS specimen was found in this period">not tracked in LIS</span>
                        )}
                      </>
                    ),
                  },
                  { key: 'volume', header: 'Volume', align: 'right', sortable: true, render: (v) => <span className="font-mono">{v == null ? '—' : fmtCount(v)}</span> },
                  { key: 'totalBilled', header: 'Billed', align: 'right', sortable: true, render: (v) => <span className="font-mono">{fmtCurrency(v)}</span> },
                  { key: 'totalCollected', header: 'Collected', align: 'right', sortable: true, render: (v) => <span className="font-mono text-success">{fmtCurrency(v)}</span> },
                ]}
              />
              {filteredByTest.length > 0 && (
                <div className="flex items-center justify-between px-4 py-2.5 border border-t-0 border-border rounded-b-md bg-muted/20 text-sm font-semibold -mt-px">
                  <span>Total</span>
                  <span className="flex gap-8 font-mono">
                    <span>{fmtCount(filteredByTest.reduce((s, t) => s + (t.volume || 0), 0))}</span>
                    <span>{fmtCurrency(filteredByTest.reduce((s, t) => s + t.totalBilled, 0))}</span>
                    <span className="text-success">{fmtCurrency(filteredByTest.reduce((s, t) => s + t.totalCollected, 0))}</span>
                  </span>
                </div>
              )}
            </div>

            {/* ── Turnaround / status breakdown (bonus) ── */}
            <div className="bg-card rounded-lg border shadow-sm overflow-hidden">
              <div className="p-4 border-b bg-muted/30">
                <h3 className="font-semibold text-sm">Specimen Status</h3>
                <p className="text-xs text-muted-foreground">Turnaround breakdown for the period</p>
              </div>
              <div className="p-4 space-y-2.5">
                {statusBreakdown.length === 0 ? (
                  <p className="text-sm text-muted-foreground text-center py-6">No specimens in this period.</p>
                ) : statusBreakdown.map(s => (
                  <div key={s.status} className="flex items-center justify-between">
                    <StatusBadge status={s.status} map={SPECIMEN_STATUS_TONE_MAP} className="capitalize" />
                    <span className="text-sm font-mono font-medium">{fmtCount(s.count)}</span>
                  </div>
                ))}
              </div>
            </div>
          </div>
        </div>
      )}
    </ReportSubPageShell>
  );
}

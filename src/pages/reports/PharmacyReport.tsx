import React, { useState, useEffect, useCallback } from 'react';
import { Pill, Users, Package, DollarSign, Loader2, TrendingUp, TrendingDown } from 'lucide-react';
import { ReportSubPageShell } from './ReportSubPageShell';
import { ReportLetterhead } from './ReportLetterhead';
import { AdvancedDataTable } from '@/components/common/DataTable/AdvancedDataTable';
import { authFetch } from '@/api/apiClient';
import { useAuth } from '@/contexts/AuthContext';
import { fmtCurrency, fmtCount, CsvColumn } from '@/utils/reportUtils';
import { toast } from '@/lib/notify';

// ── Types ────────────────────────────────────────────────────────────────

interface ByDrugRow {
  drugId: string | null;
  drugName: string;
  events: number | null;
  qty: number | null;
  dispensingValue: number;
  totalBilled: number;
  totalCollected: number;
}

interface StatusRow {
  status: string;
  count: number;
}

interface MovementItem {
  itemId: string;
  itemName: string;
  quantityOnHand: number;
  qtyDispensed: number;
  dispensingValue: number;
}

interface PharmacyReportData {
  period: { dateFrom: string; dateTo: string };
  clinicId: number;
  dispensingVolume: {
    totalEvents: number;
    distinctPatients: number;
    totalQty: number;
    totalDispensingValue: number;
  };
  cashSummary: {
    totalBilled: number;
    totalCollected: number;
    collectionMethod: { exactItems: number; estimatedItems: number; note: string };
  };
  byDrug: ByDrugRow[];
  statusBreakdown: StatusRow[];
  movement: { fastMoving: MovementItem[]; slowMoving: MovementItem[] };
}

const toLocalDateStr = (d: Date) => {
  const yyyy = d.getFullYear();
  const mm = String(d.getMonth() + 1).padStart(2, '0');
  const dd = String(d.getDate()).padStart(2, '0');
  return `${yyyy}-${mm}-${dd}`;
};

// ── Component ────────────────────────────────────────────────────────────

export default function PharmacyReport() {
  const { user } = useAuth();
  const clinicId = user?.clinic || 1;

  const [dateFrom, setDateFrom] = useState(() => toLocalDateStr(new Date(Date.now() - 29 * 86400000)));
  const [dateTo, setDateTo] = useState(() => toLocalDateStr(new Date()));
  const [loading, setLoading] = useState(true);
  const [data, setData] = useState<PharmacyReportData | null>(null);
  const [generatedAt, setGeneratedAt] = useState<Date | null>(null);

  const fetchData = useCallback(async () => {
    setLoading(true);
    try {
      const params = new URLSearchParams({ dateFrom, dateTo, clinic_id: String(clinicId) });
      const res = await authFetch(`/api/reports-v2/pharmacy?${params}`, { credentials: 'include' });
      if (!res.ok) throw new Error('Failed to load pharmacy report');
      setData(await res.json());
      setGeneratedAt(new Date());
    } catch (e: any) {
      console.error(e);
      toast.error(e?.message || 'Failed to load pharmacy report');
    } finally {
      setLoading(false);
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [dateFrom, dateTo, clinicId]);

  useEffect(() => { fetchData(); }, [fetchData]);

  const byDrug = data?.byDrug || [];
  const statusBreakdown = data?.statusBreakdown || [];
  const fastMoving = data?.movement.fastMoving || [];
  const slowMoving = data?.movement.slowMoving || [];

  const csvColumns: CsvColumn[] = [
    { header: 'Drug', key: 'drugName' },
    { header: 'Dispensing Events', key: 'events', transform: v => (v == null ? 'n/a' : fmtCount(v)) },
    { header: 'Qty Dispensed', key: 'qty', transform: v => (v == null ? 'n/a' : fmtCount(v)) },
    { header: 'Dispensing Value', key: 'dispensingValue', transform: v => fmtCurrency(v) },
    { header: 'Billed', key: 'totalBilled', transform: v => fmtCurrency(v) },
    { header: 'Collected', key: 'totalCollected', transform: v => fmtCurrency(v) },
  ];

  return (
    <ReportSubPageShell
      title="Pharmacy Report"
      description="Dispensing volume and cash value generated by the pharmacy"
      dateFrom={dateFrom}
      dateTo={dateTo}
      onDateFromChange={setDateFrom}
      onDateToChange={setDateTo}
      onRefresh={fetchData}
      loading={loading}
      csvData={byDrug}
      csvColumns={csvColumns}
      csvFilename={`pharmacy-report-${dateFrom}-${dateTo}.csv`}
    >
      <ReportLetterhead title="Pharmacy Report" dateFrom={dateFrom} dateTo={dateTo} generatedAt={generatedAt} />
      {loading && !data ? (
        <div className="flex items-center justify-center h-64">
          <Loader2 className="h-8 w-8 animate-spin text-primary" />
        </div>
      ) : (
        <div className="space-y-6">
          {/* ── Stat tiles ── */}
          <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-4">
            <div className="bg-card rounded-lg border shadow-sm p-4">
              <div className="flex items-center justify-between">
                <div>
                  <p className="text-xs uppercase tracking-wide text-muted-foreground font-medium">Dispensing Events</p>
                  <p className="text-2xl font-bold mt-1">{fmtCount(data?.dispensingVolume.totalEvents)}</p>
                  <p className="text-xs text-muted-foreground mt-0.5">{fmtCount(data?.dispensingVolume.totalQty)} units dispensed</p>
                </div>
                <Pill className="h-5 w-5 text-primary" />
              </div>
            </div>

            <div className="bg-card rounded-lg border shadow-sm p-4">
              <div className="flex items-center justify-between">
                <div>
                  <p className="text-xs uppercase tracking-wide text-muted-foreground font-medium">Patients Dispensed To</p>
                  <p className="text-2xl font-bold mt-1">{fmtCount(data?.dispensingVolume.distinctPatients)}</p>
                  <p className="text-xs text-muted-foreground mt-0.5">unique patients in period</p>
                </div>
                <Users className="h-5 w-5 text-primary" />
              </div>
            </div>

            <div className="bg-card rounded-lg border shadow-sm p-4">
              <div className="flex items-center justify-between">
                <div>
                  <p className="text-xs uppercase tracking-wide text-muted-foreground font-medium">Dispensing Value</p>
                  <p className="text-2xl font-bold mt-1">{fmtCurrency(data?.dispensingVolume.totalDispensingValue)}</p>
                  <p className="text-xs text-muted-foreground mt-0.5">drug price &times; qty at time dispensed</p>
                </div>
                <Package className="h-5 w-5 text-primary" />
              </div>
            </div>

            <div className="bg-card rounded-lg border shadow-sm p-4">
              <div className="flex items-center justify-between">
                <div>
                  <p className="text-xs uppercase tracking-wide text-muted-foreground font-medium">Billed / Collected</p>
                  <p className="text-2xl font-bold mt-1 text-success">{fmtCurrency(data?.cashSummary.totalCollected)}</p>
                  <p className="text-xs text-muted-foreground mt-0.5">of {fmtCurrency(data?.cashSummary.totalBilled)} billed via Patient Bills</p>
                </div>
                <DollarSign className="h-5 w-5 text-primary" />
              </div>
            </div>
          </div>

          {/* ── Fast / Slow moving items ── */}
          <div className="grid grid-cols-1 lg:grid-cols-2 gap-6">
            <div>
              <div className="mb-2 flex items-center gap-1.5">
                <TrendingUp className="h-4 w-4 text-primary" />
                <h3 className="font-semibold text-sm">Fast Moving Items</h3>
              </div>
              <AdvancedDataTable<MovementItem>
                headerClassName="bg-info-bg dark:bg-info/40 border-b border-border"
                data={fastMoving}
                keyExtractor={(row) => row.itemId}
                emptyMessage="No items dispensed in this period."
                columns={[
                  { key: 'itemName', header: 'Item', sortable: true },
                  { key: 'qtyDispensed', header: 'Qty Dispensed', align: 'right', sortable: true, render: (v) => <span className="font-mono font-medium">{fmtCount(v)}</span> },
                  { key: 'quantityOnHand', header: 'On Hand', align: 'right', sortable: true, render: (v) => <span className="font-mono text-muted-foreground">{fmtCount(v)}</span> },
                ]}
              />
            </div>
            <div>
              <div className="mb-2 flex items-center gap-1.5">
                <TrendingDown className="h-4 w-4 text-primary" />
                <h3 className="font-semibold text-sm">Slow Moving Items</h3>
              </div>
              <AdvancedDataTable<MovementItem>
                headerClassName="bg-info-bg dark:bg-info/40 border-b border-border"
                data={slowMoving}
                keyExtractor={(row) => row.itemId}
                emptyMessage="No active inventory items found."
                columns={[
                  { key: 'itemName', header: 'Item', sortable: true },
                  { key: 'qtyDispensed', header: 'Qty Dispensed', align: 'right', sortable: true, render: (v) => <span className={`font-mono font-medium ${v === 0 ? 'text-warning' : ''}`}>{fmtCount(v)}</span> },
                  { key: 'quantityOnHand', header: 'On Hand', align: 'right', sortable: true, render: (v) => <span className="font-mono text-muted-foreground">{fmtCount(v)}</span> },
                ]}
              />
            </div>
          </div>

          {/* ── By-drug breakdown table ── */}
          <div>
            <div className="mb-2">
              <h3 className="font-semibold text-sm">Dispensing by Drug</h3>
              <p className="text-xs text-muted-foreground">{fmtCount(byDrug.length)} drug{byDrug.length === 1 ? '' : 's'} dispensed or billed in period</p>
            </div>
            <AdvancedDataTable<ByDrugRow>
              headerClassName="bg-info-bg dark:bg-info/40 border-b border-border"
              footerRow={(colSpan) => (
                <tr className="border-t-2 border-foreground/30 bg-info-bg dark:bg-info/20 font-semibold">
                  <td colSpan={colSpan} className="px-4 py-2.5 text-sm">
                    <div className="flex justify-between items-center">
                      <span>Total Collected</span>
                      <span className="font-mono text-base border-b-2 border-double border-foreground pb-0.5">{fmtCurrency(data?.cashSummary.totalCollected)}</span>
                    </div>
                  </td>
                </tr>
              )}
              data={byDrug}
              keyExtractor={(row) => row.drugId ?? row.drugName}
              searchable
              searchPlaceholder="Search drugs..."
              emptyMessage="No dispensing or pharmacy billing activity found for the selected period."
              columns={[
                { key: 'drugName', header: 'Drug', sortable: true },
                { key: 'events', header: 'Events', align: 'right', sortable: true, render: (v) => (v == null ? '—' : fmtCount(v)) },
                { key: 'qty', header: 'Qty Dispensed', align: 'right', sortable: true, render: (v) => (v == null ? '—' : fmtCount(v)) },
                { key: 'dispensingValue', header: 'Dispensing Value', align: 'right', sortable: true, render: (v) => fmtCurrency(v) },
                { key: 'totalBilled', header: 'Billed', align: 'right', sortable: true, render: (v) => fmtCurrency(v) },
                { key: 'totalCollected', header: 'Collected', align: 'right', sortable: true, render: (v) => <span className="text-success">{fmtCurrency(v)}</span> },
              ]}
            />
          </div>

          {/* ── Status breakdown ── */}
          {statusBreakdown.length > 0 && (
            <div className="bg-card rounded-lg border shadow-sm overflow-hidden">
              <div className="p-4 border-b bg-muted/30">
                <h3 className="font-semibold text-sm">Dispensing Status Breakdown</h3>
              </div>
              <div className="p-4 flex flex-wrap gap-3">
                {statusBreakdown.map(s => (
                  <div key={s.status} className="flex items-center gap-2 bg-muted/40 rounded-md px-3 py-1.5">
                    <span className="text-sm capitalize">{s.status}</span>
                    <span className="text-sm font-mono font-semibold">{fmtCount(s.count)}</span>
                  </div>
                ))}
              </div>
            </div>
          )}
        </div>
      )}
    </ReportSubPageShell>
  );
}
